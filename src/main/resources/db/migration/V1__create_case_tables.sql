CREATE TABLE BM_CASE (
    CASE_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PAN VARCHAR(10) NOT NULL,
    UNIQUE_ID VARCHAR(30),
    NAME_OF_ASSESSEE VARCHAR(60) NOT NULL,
    DESCRIPTION VARCHAR(200) NOT NULL,
    SOURCE_OF_INFO VARCHAR(50) NOT NULL,
    DETAILS_OF_ASSET_INCOME VARCHAR(150) NOT NULL,
    ASSIGN_TO VARCHAR(20),
    REMARKS VARCHAR(4000),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CREATED_BY VARCHAR(75) NOT NULL,
    CREATION_DATE TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    LAST_UPDATED_BY VARCHAR(75),
    LAST_UPDATE_DATE TIMESTAMP
);

CREATE TABLE BM_CASE_NOTING (
    NOTING_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CASE_ID BIGINT NOT NULL,
    NOTING_NAME VARCHAR(150) NOT NULL,
    NOTING_TEXT VARCHAR(4000),
    CONSTRAINT FK_BM_NOTING_CASE FOREIGN KEY (CASE_ID) REFERENCES BM_CASE(CASE_ID)
);

CREATE TABLE BM_CASE_ATTACHMENT (
    ATTACHMENT_ID BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOTING_ID BIGINT NOT NULL,
    ORIGINAL_FILE_NAME VARCHAR(255) NOT NULL,
    STORAGE_KEY VARCHAR(500) NOT NULL,
    CONTENT_TYPE VARCHAR(150),
    FILE_SIZE BIGINT NOT NULL,
    CATEGORY VARCHAR(100),
    DESCRIPTION VARCHAR(500),
    UPLOADED_BY VARCHAR(75) NOT NULL,
    UPLOADED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT FK_BM_ATTACHMENT_NOTING FOREIGN KEY (NOTING_ID) REFERENCES BM_CASE_NOTING(NOTING_ID)
);

CREATE INDEX IX_BM_CASE_PAN ON BM_CASE(PAN);
CREATE INDEX IX_BM_CASE_STATUS ON BM_CASE(STATUS);
